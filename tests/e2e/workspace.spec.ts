import { expect, test } from '@playwright/test'
test('reference layout, reading, search and browser history', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '全部文章', exact: true })).toBeVisible()
  const sidebar = await page.getByRole('complementary', { name: '侧边栏' }).boundingBox()
  expect(sidebar?.width).toBe(248)
  await page
    .getByRole('button', { name: /LoRA 再探/ })
    .first()
    .click()
  await expect(page.getByRole('button', { name: '原文快照', exact: true })).toBeVisible()
  const readingUrl = page.url()
  await page.reload()
  await expect(page.getByRole('button', { name: '原文快照', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '回到总览', exact: true }).click()
  await expect(page.getByRole('heading', { name: '已收录 12 篇文章' })).toBeVisible()
  await page.goBack()
  expect(page.url()).toBe(readingUrl)
  await expect(page.getByRole('button', { name: '原文快照', exact: true })).toBeVisible()
  await page.getByPlaceholder('搜索标题、摘要、正文、链接').fill('DDPM')
  await expect(page.getByRole('heading', { name: '搜索结果', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByPlaceholder('搜索标题、摘要、正文、链接')).toHaveValue('DDPM')
  expect(errors).toEqual([])
})
test('language switching is instant, persistent and content-safe', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '设置', exact: true }).click()
  await page.getByLabel('界面语言', { exact: true }).selectOption('en')
  await expect(page.locator('html')).toHaveAttribute('lang', 'en')
  await expect(page.getByRole('heading', { name: 'Settings & status', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Interface language', { exact: true })).toHaveValue('en')
  await page.getByRole('tab', { name: 'Tag library', exact: true }).click()
  await expect(page.getByText('Articles and websites share the same tags.', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Articles 12', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'All Articles', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: /LoRA 再探/ }).first()).toBeVisible()
  await expect(page.getByText('October 12 · Monday', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Websites 6', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'All Websites', exact: true })).toBeVisible()
  await expect(page.getByText('6 websites', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Mobbin: view details', exact: true }).click()
  await expect(page.getByText('Freemium', { exact: true })).toBeVisible()
  await expect(page.locator('body')).not.toContainText('{{')
})
test('narrow layout opens navigation and reader without overflow', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: '打开导航', exact: true }).click()
  await page.getByRole('button', { name: '网站 6', exact: true }).click()
  await expect(page.getByRole('heading', { name: '全部网站', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Mobbin，查看详情', exact: true }).click()
  await expect(page.getByRole('button', { name: '关闭', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
test('tag and collection management retain local edits', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '设置', exact: true }).click()
  await page.getByRole('tab', { name: '合集管理', exact: true }).click()
  await page.getByRole('button', { name: '新建合集', exact: true }).last().click()
  await page.getByPlaceholder('合集名称', { exact: true }).fill('UI test collection')
  await page.getByRole('button', { name: '创建', exact: true }).click()
  await page.reload()
  await expect(page.getByText('UI test collection', { exact: true }).last()).toBeVisible()
})
